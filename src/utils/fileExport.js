/**
 * Utility functions for exporting and downloading summaries
 */

export function downloadFile(filename, content, mimeType = 'text/plain;charset=utf-8') {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = filename;
  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);
  URL.revokeObjectURL(url);
}

export function exportSummaryAsText({ title, summary, length, originalWordCount, summaryWordCount, createdAt }) {
  const dateStr = new Date(createdAt || Date.now()).toLocaleString();
  const content = `=====================================================
AI TEXT SUMMARIZER - EXPORT
=====================================================
Title: ${title || 'Document Summary'}
Date Generated: ${dateStr}
Length Mode: ${length || 'Medium'}
Original Word Count: ${originalWordCount || 0} words
Summary Word Count: ${summaryWordCount || 0} words
Reduction: ${originalWordCount && summaryWordCount ? Math.round(((originalWordCount - summaryWordCount) / originalWordCount) * 100) : 0}%

----------------- SUMMARY CONTENT -------------------
${summary}

=====================================================
Generated with AI Text Summarizer (Powered by Google Gemini)
`;

  const safeFilename = (title || 'summary')
    .toLowerCase()
    .replace(/[^a-z0-9]/g, '-')
    .substring(0, 30)
    .replace(/-+/g, '-');
  downloadFile(`${safeFilename}-${Date.now()}.txt`, content, 'text/plain;charset=utf-8');
}

export function exportSummaryAsMarkdown({ title, summary, length, originalWordCount, summaryWordCount, createdAt, originalText }) {
  const dateStr = new Date(createdAt || Date.now()).toLocaleDateString();
  const reduction = originalWordCount && summaryWordCount ? Math.round(((originalWordCount - summaryWordCount) / originalWordCount) * 100) : 0;
  
  const content = `# ${title || 'Document Summary'}

> Generated by **AI Text Summarizer** on ${dateStr}

| Metric | Value |
| :--- | :--- |
| **Length Mode** | ${length || 'Medium'} |
| **Original Words** | ${originalWordCount || 0} |
| **Summary Words** | ${summaryWordCount || 0} |
| **Efficiency Saved** | ${reduction}% reduction |

---

## 📌 Executive Summary

${summary}

${originalText ? `
---

<details>
<summary><b>Click to expand Original Source Text</b></summary>

\`\`\`text
${originalText}
\`\`\`

</details>
` : ''}

---
*Created with AI Text Summarizer*
`;

  const safeFilename = (title || 'summary')
    .toLowerCase()
    .replace(/[^a-z0-9]/g, '-')
    .substring(0, 30)
    .replace(/-+/g, '-');
  downloadFile(`${safeFilename}-${Date.now()}.md`, content, 'text/markdown;charset=utf-8');
}

export async function copyToClipboard(text) {
  try {
    if (navigator.clipboard && window.isSecureContext) {
      await navigator.clipboard.writeText(text);
      return true;
    } else {
      // Fallback for older contexts
      const textArea = document.createElement('textarea');
      textArea.value = text;
      textArea.style.position = 'fixed';
      textArea.style.left = '-999999px';
      textArea.style.top = '-999999px';
      document.body.appendChild(textArea);
      textArea.focus();
      textArea.select();
      const successful = document.execCommand('copy');
      document.body.removeChild(textArea);
      return successful;
    }
  } catch (err) {
    console.error('Failed to copy to clipboard:', err);
    return false;
  }
}
